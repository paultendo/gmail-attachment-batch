import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = file => fs.readFileSync(path.join(root,file),'utf8');
let source = read('gmail-attachment-batch.user.js');
const licence = read('LICENSE');
const attribution = read('ATTRIBUTION.md');
const licenceBlock = '/* BEGIN ATTACHMENT BATCH LICENCE\n' + licence + '\n--- PROJECT ATTRIBUTION NOTICE (GPLv3 section 7(b)) ---\n' + attribution + 'END ATTACHMENT BATCH LICENCE */';
if(!source.includes('/* BEGIN ATTACHMENT BATCH LICENCE')) throw Error('Standalone userscript licence marker missing');
source = source.replace(/\/\* BEGIN ATTACHMENT BATCH LICENCE[\s\S]*?END ATTACHMENT BATCH LICENCE \*\//,licenceBlock);
fs.writeFileSync(path.join(root,'gmail-attachment-batch.user.js'),source);
const version = source.match(/^\/\/ @version\s+(\S+)/m)[1];
let html = read('install.html');
const marker = '<script>const source=', start = html.indexOf(marker) + marker.length;
const end = html.indexOf(";document.getElementById('source').value=source;", start);
if(start < marker.length || end < start) throw Error('Installer source boundaries not found');
const encoded = JSON.stringify(source).replace(/[<>&]/g, char => ({'<':'\\u003c','>':'\\u003e','&':'\\u0026'}[char]));
html = html.slice(0,start) + encoded + html.slice(end);
fs.writeFileSync(path.join(root,'install.html'),html);
const verification = JSON.parse(read('verification.json'));
verification.version = version;
verification.script_sha256 = createHash('sha256').update(source).digest('hex');
fs.writeFileSync(path.join(root,'verification.json'),JSON.stringify(verification,null,2)+'\n');
const files = ['gmail-attachment-batch.user.js','README.md','LICENSE','ATTRIBUTION.md','PUBLISHING.md','CONTRIBUTING.md','CONTRIBUTORS.md','.gitignore','.github/ISSUE_TEMPLATE/bug_report.yml','install.html','demo.html','verification.json','package.json','package-lock.json','tests/batch.test.cjs','scripts/package.mjs','docs/assets/toolbar.png','docs/assets/setup.png','docs/assets/how-to-use.png','docs/assets/review-table.png','docs/TECHNICAL.md'];
// Explicit allowlist: private evidence and mailbox files never enter the ZIP.
const python = "import sys,zipfile; from pathlib import Path; root=Path(sys.argv[1]); names=sys.argv[2:]; out=root/'gmail-attachment-batch-prototype.zip'; z=zipfile.ZipFile(out,'w',zipfile.ZIP_DEFLATED); [z.write(root/n,'gmail-attachment-batch/'+n) for n in names]; z.close(); z=zipfile.ZipFile(out); assert z.testzip() is None";
execFileSync('python3',['-c',python,root,...files]);
console.log(`Built v${version}: installer, verification hash and public ZIP (${files.length} files).`);
